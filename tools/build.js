#!/usr/bin/env node
// Generates torrentio-streams.js and manifest.json from rex.torrentio.js.
//
//   node tools/build.js
//
// rex.torrentio.js is the only file to edit. Rex 1.1 drops a `type: "stream"` module from a
// widget that also has a list, so the same code is also published as a second, resource-only
// widget ("Torrentio Streams"). It has no settings of its own: it reads the ones the main widget
// shares through Widget.sharedCache.
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const RAW = "https://raw.githubusercontent.com/mustafabshakimuddin-cloud/rex-addon/main";
const source = fs.readFileSync(path.join(root, "rex.torrentio.js"), "utf8");

const metaStart = source.indexOf("WidgetMetadata = {");
const metaEnd = source.indexOf("\n};\n", metaStart);
if (metaStart < 0 || metaEnd < 0) throw new Error("WidgetMetadata block not found");
const body = source.slice(metaEnd + "\n};\n".length);
const main = new Function(source + "\nreturn WidgetMetadata;")();

const streams = {
  id: "community.torrentio.streams",
  title: "Torrentio Streams",
  version: main.version,
  requiredVersion: main.requiredVersion,
  description: "Torrentio 播放资源，设置在 Torrentio 模块中填写",
  author: main.author,
  site: main.site,
  iconurl: main.iconurl,
  i18n: {
    en: {
      "Torrentio 播放资源，设置在 Torrentio 模块中填写": "Torrentio playback sources; configure them in the Torrentio module",
      "加载资源": "Load Streams",
    },
    "zh-Hant": {
      "Torrentio 播放资源，设置在 Torrentio 模块中填写": "Torrentio 播放資源，設定在 Torrentio 模組中填寫",
      "加载资源": "載入資源",
    },
  },
  modules: [
    {
      // id 需固定为 loadResource
      id: "loadResource",
      title: "加载资源",
      functionName: "loadResource",
      type: "stream",
      cacheDuration: 600,
      params: [],
    },
  ],
};

const streamsSource = `/**
 * Torrentio Streams — GENERATED by tools/build.js from rex.torrentio.js. Do not edit.
 *
 * Resource-only twin of the Torrentio widget: Rex 1.1 drops a stream module from a widget that
 * also has a list. Settings come from the Torrentio widget through Widget.sharedCache.
 */
WidgetMetadata = ${JSON.stringify(streams, null, 2)};
${body}`;
fs.writeFileSync(path.join(root, "torrentio-streams.js"), streamsSource);

const entry = (meta, file) => {
  const i18n = {};
  for (const [lang, table] of Object.entries(meta.i18n || {})) {
    const picked = Object.fromEntries(Object.entries(table).filter(([key]) => key === meta.title || key === meta.description));
    if (Object.keys(picked).length) i18n[lang] = picked;
  }
  return {
    id: meta.id, title: meta.title, version: meta.version, requiredVersion: meta.requiredVersion,
    description: meta.description, author: meta.author, url: `${RAW}/${file}`, i18n,
  };
};
const manifest = {
  title: "Torrentio",
  description: "Torrentio torrent streams for playback through a debrid service",
  icon: main.iconurl,
  widgets: [entry(main, "rex.torrentio.js"), entry(streams, "torrentio-streams.js")],
};
fs.writeFileSync(path.join(root, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
console.log(`built torrentio-streams.js and manifest.json (version ${main.version})`);
